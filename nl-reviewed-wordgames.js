export function reviewedDutchWordCard(value) {
  const raw = String(value);
  const cat = raw.match(/^NAME (\d+) (.+?)\.(?:\nEXAMPLE \(COUNTS AS ONE\): (.+?)\. NAME (\d+) MORE\.)?$/i);
  if (cat && CATEGORY[cat[2].toUpperCase()]) {
    const head = `NOEM ${cat[1]} ${CATEGORY[cat[2].toUpperCase()].toUpperCase()}.`;
    if (!cat[3]) return head;
    const example = (CATEGORY_EXAMPLES[cat[3].toUpperCase()] || DUTCH_MEMORY_WORDS[cat[3][0] + cat[3].slice(1).toLowerCase()] ||
      SHOPPING[cat[3].toUpperCase()] || LAST_LETTER[cat[3].toUpperCase()] || RHYME[cat[3].toUpperCase()] || cat[3]);
    return `${head}\nVOORBEELD (TELT MEE): ${example.toUpperCase()}. NOEM ER NOG ${cat[4]}.`;
  }
  const solo = raw.match(/^Write as many (.+?) as possible\.$/i);
  if (solo) {
    const key = solo[1].toUpperCase();
    const category = CATEGORY[key] || CATEGORY['TYPES OF '+key];
    if (category) return `Schrijf zo veel mogelijk ${category} op.`;
  }
  const start = raw.match(/^Starting (word|rhyme word):\s*(.+)$/i);
  if (start) {
    const dictionary = start[1].toLowerCase() === 'word' ? LAST_LETTER : RHYME;
    const translation = dictionary[start[2].trim().toUpperCase()];
    if (translation) return `${start[1].toLowerCase() === 'word' ? 'Beginwoord' : 'Beginrijmwoord'}: ${translation.toUpperCase()}`;
  }
  const bought = raw.match(/^Start with:\s*(.+?)\. Add one new item every turn\.$/i);
  if (bought && SHOPPING[bought[1].toUpperCase()])
    return `Begin met: ${SHOPPING[bought[1].toUpperCase()]}. Voeg elke beurt één nieuw artikel toe.`;
  const memory = raw.match(/^SECRET WORDS — STUDY FOR (\d+) SECONDS\n(.+)$/s);
  if (memory) {
    const words = memory[2].split(/\s*•\s*/);
    if (words.every(w=>Object.hasOwn(DUTCH_MEMORY_WORDS,w)))
      return `GEHEIME WOORDEN — ${memory[1]} SECONDEN ONTHOUDEN\n` + words.map(w=>DUTCH_MEMORY_WORDS[w]).join(' • ');
  }
  const items = raw.split(/\s*•\s*/);
  if (items.length >= 8 && items.every(w=>Object.hasOwn(DUTCH_MEMORY_WORDS,w)))
    return items.map(w=>DUTCH_MEMORY_WORDS[w]).join(' • ');
  const reaction = raw.match(/^CALLER: READ ONE NUMBER EVERY (\d+) SECONDS\.\n([^\n]+)\n\n([\s\S]+)$/);
  if (reaction && Object.hasOwn(REACTION,reaction[2]))
    return `VOORLEZER: NOEM ELKE ${reaction[1]} SECONDEN ÉÉN GETAL.\n${REACTION[reaction[2]]}\n\n` +
      reaction[3].replace(/← SWITCH NOW/g,'← WISSEL NU VAN REGEL');
  return null;
}
