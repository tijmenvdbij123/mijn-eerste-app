import fs from 'node:fs';
import {TOPIC_FACTS} from './src/packs/topic-trivia.js';
import {REVIEWED_DUTCH_CLASSIC_QUESTIONS} from './src/i18n/nl-reviewed-classic.js';
import {REVIEWED_DUTCH_ANSWERS} from './src/i18n/nl-reviewed-answers.js';
import {REVIEWED_DUTCH_DRAW_ITEMS,REVIEWED_DUTCH_DRAW_THEMES} from './src/i18n/nl-reviewed-visual.js';
import {REVIEWED_DUTCH_HEADLINES} from './src/i18n/nl-reviewed-headlines.js';
import {REVIEWED_DUTCH_SHAPES} from './src/i18n/nl-reviewed-shapes.js';
import {REVIEWED_DUTCH_STORY_THEMES} from './src/i18n/nl-reviewed-stories.js';
import {REVIEWED_DUTCH_ACTIONS} from './src/i18n/nl-reviewed-actions.js';
import {danish} from './src/i18n/da.js';
const group=[];
for(const [topic,levels] of Object.entries(TOPIC_FACTS))for(const [lv,rows] of Object.entries(levels))for(const row of rows)group.push([`topic/${topic}/${lv}`,row[0],danish(row[0])],[`topic/${topic}/${lv}`,row[2],danish(row[2])]);
for(const [x,y] of Object.entries(REVIEWED_DUTCH_CLASSIC_QUESTIONS))group.push(['classic',x,danish(x)]);
for(const [x,y] of Object.entries(REVIEWED_DUTCH_ANSWERS))group.push(['answers',x,danish(x)]);
for(const [name,ob] of Object.entries({actions:REVIEWED_DUTCH_ACTIONS,shapes:REVIEWED_DUTCH_SHAPES,visual_items:REVIEWED_DUTCH_DRAW_ITEMS,visual_themes:REVIEWED_DUTCH_DRAW_THEMES,headlines:REVIEWED_DUTCH_HEADLINES,stories:REVIEWED_DUTCH_STORY_THEMES}))for(const [x,y] of Object.entries(ob))group.push([name,x,danish(x)]);
const esc=x=>x.replaceAll('\t',' ').replaceAll('\n',' ↵ ');
fs.writeFileSync('/mnt/data/lrb48-inventory.tsv', 'group\tenglish\tcurrentDanish\n'+group.map(row=>row.map(esc).join('\t')).join('\n'));
console.log('content counts',Object.groupBy(group,x=>x[0].split('/')[0]));console.log('total',group.length);
