const LEVELS = ["novice","amateur","intermediate","competent","skilled","advanced","grandmaster"];
function cardFor(entries, offset) {
  const chosen = Array.from({length:5}, (_,i) => entries[(offset*3+i*2)%entries.length]);
  const languageVariants = Object.fromEntries(["en","nl","da"].map((lang)=>[
    lang, {
      text: chosen.map((entry,i) => `${i+1}. ${entry.definition[lang]}`).join("\n"),
      answer: chosen.map((entry,i) => `${i+1}. ${entry.answer[lang]}`).join("\n")
    }
  ]));
  return {...languageVariants.en, languageVariants, dictionaryCard:true, source:"Wiktionary / ANW / DDO"};
}
export const DICTIONARY_PACKS = {
  "dictionary-definitions": Object.fromEntries(LEVELS.map(level => [level, {
    prompts: Array.from({length:5},(_,idx)=>cardFor(DICTIONARY_LEXICON[level],idx))
  }]))
};
export function dictionaryReference(answer,lang="en") {
  const url = lang === "da" ? "https://ordnet.dk/ddo/ordbog?query=" : lang === "nl" ? "https://anw.ivdnt.org/search?query=" : "https://en.wiktionary.org/wiki/";
  return url + encodeURIComponent(answer.replace(/ /g, lang === "en" ? "_" : " "));
}
